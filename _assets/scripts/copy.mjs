/**
 * THE COPY LOOKUP — one way to retrieve a user-visible string, in every runtime.
 *
 * [decided 2026-09-07, owner] `site.copy.json` holds every string a VISITOR reads; `site.config.json`
 * holds what the MODEL reads. This is the reader for the first of those, and it is deliberately the
 * ONLY one: *"there should be one consistent way to retrieve copy in the codebase."*
 *
 * It takes the data rather than loading it, because the four runtimes get it four different ways and
 * only the LOADING differs:
 *   • the Node build      `require('../site.copy.json')`            — Node reads JSON natively
 *   • the MCP apps        the same, at build time                   — they are generated by the build
 *   • the Cloud Function  `require('./copy.json')`                  — written into the deploy bundle
 *   • the BROWSER         `copy-data.mjs`, generated at build time  — a browser cannot import JSON yet
 *
 * [hard] THE BROWSER GETS EVERY LOCALE (owner): a language switch then needs no mechanism at all,
 * and there is ONE version of each script rather than one per locale. It costs nothing to speak of —
 * every file that carries copy is in `main.js`'s single module graph, so the total is the same
 * whether the strings sit in one module or eight.
 */

import { pickLocale, isI18nValue } from './i18n-core.mjs';
// The plural rule lives in its own file so the offline page's inlined script can be handed the
// SAME source rather than a second copy of it. See the note at the top of plural.mjs.
import { PLURAL_CATEGORIES, categoriesFor, isPluralForms, pluralize } from './plural.mjs';
export { PLURAL_CATEGORIES, isPluralForms, pluralize };

/**
 * @param {object} data  `site.copy.json` — `{ <key>: { context, text: { <locale>: string } } }`
 * @param {object} cfg   `{ locales, primary, fallback }` from `site.config.json`
 * @returns {(key: string, locale?: string) => string}
 */
export function makeCopy(data, cfg) {
  return function copy(key, locale = cfg.primary) {
    const entry = data[key];
    // [hard] A MISSING KEY THROWS, and it can only be a typo: `validateCopy` checks the whole file at
    // build time and the browser is handed what that validated. A string silently resolving to '' is
    // how a label disappears from a page and nobody notices for a month.
    if (!entry) throw new Error(`copy: no such key "${key}" in site.copy.json`);
    const { value } = pickLocale(entry.text, locale, cfg);
    if (value === undefined) throw new Error(`copy: "${key}" has no value for "${locale}" or its fallbacks`);
    // [hard] A PLURAL KEY THROWS HERE RATHER THAN HANDING BACK THE OBJECT. Returning it would render
    // `[object Object]`, which is the exact failure the "a locale holds a string" rule was written to
    // prevent — allowing forms must not reintroduce it through the front door.
    if (isPluralForms(value)) {
      throw new Error(`copy: "${key}" has plural forms — call pluralize(copy(key), count) with the count`);
    }
    return value;
  };
}

/**
 * `fill('must be {%1%} or more', 3)` — TEMPLATING, deliberately NOT a second way to RETRIEVE.
 *
 * [hard] ONE RETRIEVAL FUNCTION, ONE TEMPLATING FUNCTION. `copy(key, locale)` answers *what does this
 * site say*; this answers *put these values in it*. A `copy(key, vars)` overload would have made one
 * function do two jobs and would have collided with the locale argument — the `resolveField` mistake
 * this codebase already records (two jobs in one function is what made "where do the checks live?"
 * unanswerable).
 *
 * [hard, owner 2026-10-06] THE PLACEHOLDER IS A NUMBER, `{%1%}`, `{%2%}`, and the values come IN
 * ORDER: `{%1%}` is the first value given, `{%2%}` the second. It was `{name}` from an object, and a
 * NAME IS A WORD — a translator, and above all a translating AI, translates words, so `{category}`
 * would come back as `{categorie}` and stop working in the one locale nobody building the feature
 * reads. A number has no word in it. What each number holds is said in the entry's `context`, as a
 * WordPress string says it in a `translators:` comment; `copy.test.js` checks both.
 *
 * [hard] A MISSING VALUE THROWS. Left alone it would ship the literal `{%1%}` to a visitor — the same
 * silent-empty-string failure `copy()` refuses a missing key for.
 */
export function fill(text, ...values) {
  if (HAS_LINK.test(text)) throw new Error(`copy: "${text}" holds a link token — turn it into a link first (copyHtml, generator/copy.js)`);
  return text.replace(/\{%(\d+)%\}/g, (token, n) => {
    if (!(n >= 1 && n <= values.length)) throw new Error(`copy: "${text}" wants ${token}, which was not given`);
    return values[n - 1];
  });
}

/**
 * [owner 2026-10-13] A LINK IN A STRING: `{%1%}["the link text", /the/address/]`. The words a visitor reads are the string's, in its own language, and so is the address: whoever writes
 * the Dutch string writes the Dutch page's address, and nothing in the code knows which page is "the disclosure". The number is the same digits-only token as every placeholder (nothing in it can
 * be translated); what follows it in brackets is the link's text, in double quotes (`\"` for a quote), a comma and the address: a path on the site (`/x/`), a web address (`https://…`) or a
 * sponsor (`sponsor:id`, `sponsor:id/link`). The build turns it into an `<a>` (`copyHtml`, `generator/copy.js`) and checks every address exists (`checkCopyLinks`).
 */
const LINK = '\\{%(\\d+)%\\}\\[\\s*"((?:[^"\\\\]|\\\\.)*)"\\s*,\\s*([^\\]\\s]+)\\s*\\]';
const HAS_LINK = /\{%\d+%\}\[/;
const TARGET = /^(?:\/(?!\/)\S*|https?:\/\/\S+|sponsor:[a-z0-9][a-z0-9-]*(?:\/[a-z0-9][a-z0-9-]*)?)$/;

/** The link tokens of one string, in order: `[{ n, text, target }]`. A `{%N%}[` that does not parse as one is an error, naming it. */
export function copyLinks(text) {
  const out = [];
  for (const m of String(text).matchAll(new RegExp(LINK, 'g'))) out.push({ n: Number(m[1]), text: m[2].replace(/\\(.)/g, '$1'), target: m[3], raw: m[0], at: m.index });
  const heads = [...String(text).matchAll(/\{%\d+%\}\[/g)].length;
  if (heads !== out.length) throw new Error(`copy: "${text}" has a link that is not {%N%}["link text", address]`);
  for (const l of out) {
    if (!l.text.trim()) throw new Error(`copy: "${text}" has a link with no text`);
    if (!TARGET.test(l.target)) throw new Error(`copy: "${text}" links to "${l.target}", which is not a path on the site (/x/), a web address (https://…) or a sponsor (sponsor:id)`);
  }
  return out;
}

/** The string with each link token replaced by `make(link)`, and the text between them by `between(text)` — the build makes the `<a>` and escapes the rest. */
export function fillLinks(text, make, between = (s) => s) {
  let at = 0; let out = '';
  for (const l of copyLinks(text)) { out += between(String(text).slice(at, l.at)) + make(l); at = l.at + l.raw.length; }
  return out + between(String(text).slice(at));
}

/**
 * Every entry is well-formed and has a PRIMARY value. Called by the build, so a bad file fails there
 * rather than in a visitor's browser — which is what lets `copy()` above throw with a clear
 * conscience. Mirrors `i18nStrict: "primary"`: the primary locale is required, a secondary one falls
 * back and is REPORTED rather than failing.
 *
 * @returns {{ untranslated: string[] }}  keys with no value in a secondary locale
 */
const FIELDS = ['context', 'text'];

export function validateCopy(data, cfg) {
  const untranslated = [];
  for (const [key, entry] of Object.entries(data)) {
    if (!entry || typeof entry !== 'object') throw new Error(`site.copy.json: "${key}" is not an entry`);
    if (!entry.context) throw new Error(`site.copy.json: "${key}" has no "context" — say where and how it is used`);
    if (!('text' in entry)) throw new Error(`site.copy.json: "${key}" has no "text"`);

    // [hard] AN ENTRY HAS EXACTLY `context` AND `text`, AND NOTHING ELSE. An unknown key is a typo or
    // a field somebody expected to do something, and either way nothing reads it — the same rule
    // `prepareConfig` applies to a component's authored config, for the same reason: silently
    // ignoring a key is how a file grows data that looks live and is not.
    const stray = Object.keys(entry).filter((k) => !FIELDS.includes(k));
    if (stray.length) {
      throw new Error(`site.copy.json: "${key}" has ${stray.map((k) => `"${k}"`).join(', ')}, `
        + `which nothing reads. An entry is { ${FIELDS.join(', ')} }.`);
    }

    // [hard] AND `text` IS A TRANSLATION OBJECT — every key a declared locale, never a bare string.
    // This is the guard for the FILE's one silent failure: `isI18nValue` requires every key to be a
    // locale, so `{ en, nl, context }` stops being recognised, `pickLocale` hands back the OBJECT as
    // if it were the value, and the page renders `[object Object]` — while validation passes AND the
    // build reports the entry as fully translated. Nothing throws anywhere.
    //
    // It also rules out a bare `"text": "Hello"`, which would otherwise work. That is deliberate: a
    // second way to write one thing, and — worse — it would make the bug above indistinguishable
    // from a deliberate value, since both are simply "not an i18n value". A single-locale site writes
    // `{ "en": "…" }` and adding a locale is then a data change rather than a change of shape.
    if (!isI18nValue(entry.text, cfg)) {
      throw new Error(`site.copy.json: "${key}".text is not a translation object — every key must be `
        + `a declared locale (${cfg.locales.join(', ')}). A stray key here resolves to [object Object] `
        + `with nothing failing.`);
    }

    const primary = pickLocale(entry.text, cfg.primary, cfg);
    if (primary.value === undefined) throw new Error(`site.copy.json: "${key}" has no "${cfg.primary}" value`);

    // [hard] PLURAL FORMS ARE CHECKED AGAINST THE LOCALE, which is what makes a nested object
    // provably deliberate rather than provably an object. Three rules, and each one rejects a
    // different mistake:
    //   · every key is a category THAT LOCALE USES — `one` under ja and `few` under en both fail,
    //     and so does any stray key, which is the one that matters (`{ en: { text: … } }`);
    //   · `other` is present — the one category every language has, and pluralize's fallback;
    //   · ALL locales agree on whether the key is plural. A key either takes a count or it does not,
    //     and `{ en: {one,other}, nl: "…" }` would mean the Dutch page never pluralises — silently,
    //     because nothing would throw.
    // [hard] A LOCALE HOLDS A STRING OR FORMS, AND NOTHING ELSE — and this rule is NEW, not a
    // survivor of the old one. The rule everyone believed was in force ("a locale's value is a
    // string") was never actually checked: `isI18nValue` inspects the OUTER keys, so `{ en: { text:
    // 'x' } }` and `{ en: { en: 'x' } }` both validated clean, resolved to the object, and rendered
    // `[object Object]`. Measured 2026-09-17, on the code as it stood before plurals existed.
    // So allowing forms is what finally closes it: the question "is this object deliberate?" now has
    // an answer, and asking it at all is what forced the check to be written.
    for (const loc of cfg.locales) {
      const value = entry.text[loc];
      if (value === undefined || typeof value === 'string' || isPluralForms(value)) continue;
      const stray = (value && typeof value === 'object' && !Array.isArray(value))
        ? Object.keys(value).filter((k) => !PLURAL_CATEGORIES.includes(k))
        : [];
      throw new Error(`site.copy.json: "${key}".text.${loc} is ${stray.length
        ? `an object keyed by ${stray.map((k) => `"${k}"`).join(', ')}` : `a ${typeof value}`}. `
        + `A locale holds a STRING, or PLURAL FORMS keyed by ${PLURAL_CATEGORIES.join('/')} — `
        + 'anything else resolves to [object Object] on the page with nothing failing here.');
    }

    // [owner 2026-10-13] A LINK TOKEN is well-formed in every locale that has one, and its number is not also a plain placeholder of the same string (`fill` would give it a value).
    for (const loc of cfg.locales) {
      const value = entry.text[loc];
      if (typeof value !== 'string' || !HAS_LINK.test(value)) continue;
      let links;
      try { links = copyLinks(value); } catch (e) { throw new Error(`site.copy.json: "${key}".text.${loc}: ${e.message}`); }
      const plain = [...value.replace(new RegExp(LINK, 'g'), '').matchAll(/\{%(\d+)%\}/g)].map((m) => Number(m[1]));
      const clash = links.map((l) => l.n).filter((n) => plain.includes(n));
      if (clash.length) throw new Error(`site.copy.json: "${key}".text.${loc} uses {%${clash[0]}%} both as a link and as a placeholder a value fills`);
    }

    const pluralLocales = cfg.locales.filter((loc) => isPluralForms(entry.text[loc]));
    if (pluralLocales.length) {
      for (const loc of cfg.locales) {
        const value = entry.text[loc];
        if (value === undefined) continue;          // untranslated: reported below, not an error
        if (!isPluralForms(value)) {
          throw new Error(`site.copy.json: "${key}" has plural forms for `
            + `${pluralLocales.map((l) => `"${l}"`).join(', ')} but a plain string for "${loc}". `
            + 'A key either takes a count in every locale or in none.');
        }
        const allowed = categoriesFor(loc);
        const wrong = Object.keys(value).filter((c) => !allowed.includes(c));
        if (wrong.length) {
          throw new Error(`site.copy.json: "${key}".text.${loc} declares `
            + `${wrong.map((c) => `"${c}"`).join(', ')}, which "${loc}" does not use. `
            + `Its categories are ${allowed.join(', ')}.`);
        }
        if (!('other' in value)) {
          throw new Error(`site.copy.json: "${key}".text.${loc} has no "other" — `
            + 'every language has that category and it is the fallback when a count matches no other.');
        }
      }
    }
    for (const loc of cfg.locales) {
      if (loc === cfg.primary) continue;
      if (pickLocale(entry.text, loc, cfg).usedLocale !== loc) untranslated.push(`${key} (${loc})`);
    }
  }
  return { untranslated };
}
